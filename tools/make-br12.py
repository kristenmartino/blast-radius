SHOWN = [
 # id, status, test, lastOrder, orders12, engage
 ('C-001', 'open', 0, 12, 3, 5),
 ('C-002', 'open', 0, 400, 0, 30),
 ('C-003', 'closed', 0, 45, 1, -1),
 ('C-004', 'open', 1, 3, 2, 1),
 ('C-005', 'open', 0, 800, 0, 20),
 ('C-006', 'open', 0, 200, 1, 150),
 ('C-007', 'open', 0, 60, 0, -1),
 ('C-008', 'open', 0, -1, 0, -1),
 ('C-009', 'open', 0, 700, 0, -1),
 ('C-010', 'open', 0, 5, 4, 2),
 ('C-011', 'open', 0, 120, 2, 80),
 ('C-012', 'closed', 0, 500, 0, -1),
 ('C-013', 'open', 0, 30, 1, -1),
 ('C-014', 'open', 1, 20, 3, -1),
 ('C-015', 'open', 0, 300, 1, -1),
]
TEST_ROWS = {23, 46, 69, 92, 115, 138}

def customers():
    out = [dict(id=r[0], status=r[1], test=r[2], lastOrder=r[3], orders12=r[4], engage=r[5]) for r in SHOWN]
    for i in range(16, 151):
        g = (i * 7 + 3) % 10
        status, last, o12, eng = 'open', -1, 0, -1
        if g <= 3:                       # core active
            last = 2 + (i * 37) % 360
            o12 = 1 + i % 3
            eng = (i * 13) % 160 if i % 4 else -1
        elif g <= 5:                     # lapsed, 366 to 730 days
            last = 366 + (i * 53) % 365
            eng = (i * 11) % 120 if i % 2 else -1
        elif g == 6:                     # engaged by email, never ordered
            eng = (i * 17) % 90
        elif g == 7:                     # closed account
            status = 'closed'
            last = 30 + (i * 41) % 600
            o12 = 1 if last <= 365 else 0
        elif g == 8:                     # every recent order refunded
            last = 10 + (i * 29) % 300
            eng = (i * 19) % 200 if i % 3 == 0 else -1
        else:                            # inactive
            last = 731 + (i * 23) % 500 if i % 2 else -1
        out.append(dict(id='C-%03d' % i, status=status, test=1 if i in TEST_ROWS else 0, lastOrder=last, orders12=o12, engage=eng))
    return out

if __name__ == '__main__':
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'data', 'br12.json')
    inv = [dict(id=r[0], name=r[1], domain=r[2], owner=r[3], feedsBoard=r[4], refreshDays=r[5], tests=r[6], q30=r[7], cost=r[8]) for r in INV]
    cust = customers()
    assert len(inv) == 24 and len(cust) == 150 and len({c['id'] for c in cust}) == 150
    data = {'note': 'Ashgrove Outfitters (fictional): data inventory and customer extract left for the new Chief Data Officer.',
            'shown': 15, 'inventory': inv, 'customers': cust}
    with open(path, 'w') as f:
        json.dump(data, f, indent=1)
        f.write('\n')
    print('wrote', len(inv), 'datasets and', len(cust), 'customers')

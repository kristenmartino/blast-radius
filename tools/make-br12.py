"""Writes data/br12.json: Ashgrove Outfitters' data inventory (24 datasets) and customer extract (150 rows), both
fictional, for packet BR-12 (First 90 days as Chief Data Officer). The first 15 customer rows are the ones the packet
shows; the other 135 are generated by fixed arithmetic (no random numbers), so running this again writes the same file.

Inventory fields: id, name, domain, owner ('' if none), feedsBoard, refreshDays (days since last refresh), tests
(number of automated tests), q30 (queries in the last 30 days), cost (dollars a month).
Customer fields: id, status (open/closed), test (1 = internal test account), lastOrder (days since last order, -1 none),
orders12 (paid orders in the last 365 days after full refunds), engage (days since last email open, click or visit, -1 none).
The three definitions of "active customer" live in the packet, in math/numbers.js and in math/numbers.py."""
import json, os

